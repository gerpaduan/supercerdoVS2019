-- Modulo Pedidos (2026-10-19, ver docs/DECISIONS.md "Pedidos": Fase 3 de Existencia por sucursales).
--
-- Un pedido de compra armado desde Stock > Existencia por sucursales ("Ingresar pedido"): una cantidad a pedir por
-- producto y sucursal. UN pedido puede cubrir varias sucursales, por eso la cabecera no tiene sucursal propia: cada linea
-- (pedidolinea) es un par producto x sucursal con cantidad > 0.
--
--  - pedido:        cabecera. totalestimado = suma de los importes de las lineas que tienen precio; lineassinprecio = cuantas
--                   lineas no tenian precio de ultima compra (NO suman: nunca cuentan como $0 en silencio, CLAUDE.md 2.7).
--                   clientid: id que genera el navegador por pedido en curso (idempotencia: reintentar un guardado no duplica).
--  - pedidolinea:   snapshot al guardar (codigo, nombre del producto, sucursal, stock y punto de ese momento, precio de la
--                   ultima compra, proveedor y fecha de esa compra). El importe es una ESTIMACION (cantidad x ultimo precio).
--                   Al modificar un pedido las lineas que se conservan mantienen su precio guardado.
--  - pedidoevento:  historial append-only (solo INSERT/SELECT): alta y modificaciones, con quien lo hizo y, si hizo falta,
--                   quien autorizo con su clave (usuario de produccion). detalle = texto con lo que cambio.
-- Sin FOREIGN KEY declarativas (mismo criterio que el resto de esta base: integridad en la capa de negocio).
-- Aditiva e idempotente. Base unica multi-tenant (RLS por idempresa): una sola corrida cubre a todas las empresas.
-- Solo Postgres (el modulo no existe con SQL Server). Correr conectado a 'carnisys' con el rol carnisys_admin.

CREATE TABLE IF NOT EXISTS pedido (
    idpedido          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idempresa         integer NOT NULL,
    clientid          uuid,
    fecha             timestamp NOT NULL DEFAULT now(),
    idusuario         integer NOT NULL,
    usuario           text NOT NULL,
    nota              text,
    totalestimado     numeric(14,2) NOT NULL DEFAULT 0,
    lineassinprecio   integer NOT NULL DEFAULT 0,
    creado            timestamp NOT NULL DEFAULT now(),
    modificado        timestamp,
    modificadopor     integer
);

CREATE INDEX IF NOT EXISTS ix_pedido_empresa_fecha ON pedido (idempresa, fecha DESC);
CREATE UNIQUE INDEX IF NOT EXISTS ux_pedido_empresa_clientid ON pedido (idempresa, clientid) WHERE clientid IS NOT NULL;

CREATE TABLE IF NOT EXISTS pedidolinea (
    idpedidolinea     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idempresa         integer NOT NULL,
    idpedido          integer NOT NULL,
    idcorte           integer NOT NULL,
    idsucursal        integer NOT NULL,
    codigo            bigint NOT NULL DEFAULT 0,
    producto          text NOT NULL,
    sucursal          text NOT NULL,
    cantidad          numeric(14,3) NOT NULL,
    pesable           boolean NOT NULL DEFAULT false,
    promedio          numeric(14,3),
    stockactual       numeric(14,3),
    puntostock        numeric(14,3),
    preciounitario    numeric(14,4),
    proveedor         text,
    fechaprecio       timestamp,
    importe           numeric(14,2),
    CONSTRAINT ck_pedidolinea_cantidad CHECK (cantidad > 0),
    CONSTRAINT ck_pedidolinea_precio CHECK (preciounitario IS NULL OR preciounitario > 0)
);

CREATE INDEX IF NOT EXISTS ix_pedidolinea_pedido ON pedidolinea (idpedido);
CREATE UNIQUE INDEX IF NOT EXISTS ux_pedidolinea_producto_sucursal ON pedidolinea (idpedido, idcorte, idsucursal);

CREATE TABLE IF NOT EXISTS pedidoevento (
    idpedidoevento    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idempresa         integer NOT NULL,
    idpedido          integer NOT NULL,
    fecha             timestamp NOT NULL DEFAULT now(),
    tipo              varchar(20) NOT NULL,
    idusuario         integer NOT NULL,
    usuario           text NOT NULL,
    idautorizador     integer,
    autorizador       text,
    detalle           text,
    CONSTRAINT ck_pedidoevento_tipo CHECK (tipo IN ('ALTA', 'MODIFICACION'))
);

CREATE INDEX IF NOT EXISTS ix_pedidoevento_pedido ON pedidoevento (idpedido, fecha);

ALTER TABLE pedido ENABLE ROW LEVEL SECURITY;
ALTER TABLE pedidolinea ENABLE ROW LEVEL SECURITY;
ALTER TABLE pedidoevento ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS pedido_rls ON pedido;
CREATE POLICY pedido_rls ON pedido FOR ALL
    USING (current_setting('app.id_empresa', true) IS NOT NULL AND current_setting('app.id_empresa', true) <> ''
           AND idempresa = current_setting('app.id_empresa', true)::int)
    WITH CHECK (idempresa = current_setting('app.id_empresa', true)::int);

DROP POLICY IF EXISTS pedidolinea_rls ON pedidolinea;
CREATE POLICY pedidolinea_rls ON pedidolinea FOR ALL
    USING (current_setting('app.id_empresa', true) IS NOT NULL AND current_setting('app.id_empresa', true) <> ''
           AND idempresa = current_setting('app.id_empresa', true)::int)
    WITH CHECK (idempresa = current_setting('app.id_empresa', true)::int);

DROP POLICY IF EXISTS pedidoevento_rls ON pedidoevento;
CREATE POLICY pedidoevento_rls ON pedidoevento FOR ALL
    USING (current_setting('app.id_empresa', true) IS NOT NULL AND current_setting('app.id_empresa', true) <> ''
           AND idempresa = current_setting('app.id_empresa', true)::int)
    WITH CHECK (idempresa = current_setting('app.id_empresa', true)::int);

GRANT SELECT, INSERT, UPDATE, DELETE ON pedido TO carnisys_user, cs_admin_pg;
GRANT SELECT, INSERT, UPDATE, DELETE ON pedidolinea TO carnisys_user, cs_admin_pg;
-- Historial append-only: la app solo agrega y lee, nunca modifica ni borra.
GRANT SELECT, INSERT ON pedidoevento TO carnisys_user, cs_admin_pg;
GRANT USAGE, SELECT ON SEQUENCE pedido_idpedido_seq TO carnisys_user, cs_admin_pg;
GRANT USAGE, SELECT ON SEQUENCE pedidolinea_idpedidolinea_seq TO carnisys_user, cs_admin_pg;
GRANT USAGE, SELECT ON SEQUENCE pedidoevento_idpedidoevento_seq TO carnisys_user, cs_admin_pg;
