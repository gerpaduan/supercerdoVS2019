-- Autorizaciones provisorias del POS (2026-11-03, ver docs/DECISIONS.md "POS: autorizacion provisoria de otro
-- usuario"). Correr como carnisys_admin (dueno de las tablas), ANTES de desplegar el codigo.
-- Una fila por autorizacion: quien autorizo, a que operador, que accion y sobre que registro; fechafin/motivofin se
-- completan al cerrarse la ventana de la accion ('guardado', 'cerrado', 'vencido'). Solo INSERT y el UPDATE de cierre.
-- Sin particionar: crece solo cuando alguien autoriza a otro (pocas filas); desviacion de 9.3 registrada en DECISIONS.md.

CREATE TABLE IF NOT EXISTS auditoriaautorizacionespos (
    id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idempresa           integer      NOT NULL,
    posinstanceid       varchar(64)  NOT NULL,
    accion              varchar(30)  NOT NULL,
    idregistro          integer      NOT NULL DEFAULT 0,
    idoperador          integer      NOT NULL,
    idautorizador       integer      NOT NULL,
    idusuariosesion     integer      NOT NULL,
    fechaautorizacion   timestamp    NOT NULL DEFAULT now(),
    fechafin            timestamp,
    motivofin           varchar(20),
    CONSTRAINT ck_auditoriaautorizacionespos_accion CHECK (accion IN ('ModificarVenta', 'Bonificar', 'CtaCte', 'Pago', 'MisVentas'))
);

CREATE INDEX IF NOT EXISTS ix_auditoriaautorizacionespos_fecha ON auditoriaautorizacionespos (idempresa, fechaautorizacion DESC);

ALTER TABLE auditoriaautorizacionespos ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS auditoriaautorizacionespos_rls ON auditoriaautorizacionespos;
CREATE POLICY auditoriaautorizacionespos_rls ON auditoriaautorizacionespos FOR ALL
    USING (current_setting('app.id_empresa', true) IS NOT NULL AND current_setting('app.id_empresa', true) <> ''
           AND idempresa = current_setting('app.id_empresa', true)::int)
    WITH CHECK (idempresa = current_setting('app.id_empresa', true)::int);

GRANT SELECT, INSERT, UPDATE ON auditoriaautorizacionespos TO carnisys_user, cs_admin_pg;
GRANT USAGE, SELECT ON SEQUENCE auditoriaautorizacionespos_id_seq TO carnisys_user, cs_admin_pg;

