-- Historial de modificaciones de egresos de caja (2026-11-10, ver docs/DECISIONS.md "Advertencia de egresos modificados
-- por el cajero al cerrar caja"). Antes el UPDATE de egresoscaja pisaba los valores y solo quedaba actualizado/actualizadopor:
-- no habia forma de saber el monto anterior. Ahora cada modificacion desde el formulario de egreso (POS o pantalla admin)
-- inserta UNA fila con los valores de antes y de despues, en la MISMA transaccion que el UPDATE (si este INSERT falla, la
-- modificacion no se guarda). El modal "Cerrar Caja" la usa para advertir al encargado que el cajero modifico egresos.
--  - idusuario/usuario: quien modifico. Con la cuenta compartida de produccion es el OPERADOR, no la cuenta de sesion.
--  - creadoporegreso: dueno del egreso (egresoscaja.creadopor) al momento de modificar.
-- Append-only: solo INSERT/SELECT, lo registrado no se puede alterar ni borrar.
-- Aditiva e idempotente. Base unica multi-tenant (RLS por idempresa): una sola corrida cubre a todas las empresas.
-- ORDEN DE DEPLOY: correr ESTA migracion ANTES de publicar el codigo nuevo (GuardarEgresoCaja inserta aca al modificar y
-- ObtenerDatosCierre la consulta). Correr conectado a 'carnisys' con el rol carnisys_admin (dueno de las tablas).

CREATE TABLE IF NOT EXISTS auditoriaegresoscaja (
    id                      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idempresa               integer NOT NULL,
    idegresocaja            integer NOT NULL,
    idusuario               integer NOT NULL,
    usuario                 text,
    fecha                   timestamp NOT NULL DEFAULT now(),
    creadoporegreso         integer NOT NULL,
    montoanterior           double precision,
    montonuevo              double precision,
    idtipoanterior          integer,
    idtiponuevo             integer,
    fechahoraanterior       timestamp,
    fechahoranueva          timestamp,
    descripcionanterior     text,
    descripcionnueva        text,
    idsucursalanterior      integer,
    idsucursalnueva         integer
);

CREATE INDEX IF NOT EXISTS ix_auditoriaegresoscaja_egreso ON auditoriaegresoscaja (idempresa, idegresocaja);
CREATE INDEX IF NOT EXISTS ix_auditoriaegresoscaja_dueno ON auditoriaegresoscaja (idempresa, creadoporegreso, fecha);

ALTER TABLE auditoriaegresoscaja ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS auditoriaegresoscaja_rls ON auditoriaegresoscaja;
CREATE POLICY auditoriaegresoscaja_rls ON auditoriaegresoscaja FOR ALL
    USING (current_setting('app.id_empresa', true) IS NOT NULL AND current_setting('app.id_empresa', true) <> ''
           AND idempresa = current_setting('app.id_empresa', true)::int)
    WITH CHECK (idempresa = current_setting('app.id_empresa', true)::int);

GRANT SELECT, INSERT ON auditoriaegresoscaja TO carnisys_user, cs_admin_pg;
GRANT USAGE, SELECT ON SEQUENCE auditoriaegresoscaja_id_seq TO carnisys_user, cs_admin_pg;
