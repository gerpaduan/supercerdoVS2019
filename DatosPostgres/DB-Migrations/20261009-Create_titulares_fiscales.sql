-- Titulares fiscales (2026-10-09, ver docs/DECISIONS.md "Titulares fiscales por empresa y por sucursal").
-- Una empresa puede facturar con varios titulares (personas con CUIT y certificado ARCA propios).
--  - titulares_fiscales: un titular PRINCIPAL por empresa (espredeterminado = true; su CUIT es el de la empresa y sus
--    datos fiscales siguen en "empresas") y N titulares no principales (datos copiados de la persona al guardar).
--  - titulares_fiscales_ptovta: lista de puntos de venta de ARCA de un titular no principal.
--  - titulares_fiscales_sucursal: que punto de venta usa un titular no principal en una sucursal.
--  - titulares_fiscales_clave: clave (cifrada) del .pfx de los titulares no principales, APARTE de las tablas de
--    negocio: el procedimiento de reemplazo de la base de la VPS la conserva igual que certificado_arca_clave.
-- Aditiva e idempotente. Base unica multi-tenant (RLS por idempresa): una sola corrida cubre a todas las empresas.
-- ORDEN DE DEPLOY: correr ESTA migracion (y las 20261009b / 20261009c) ANTES de publicar el codigo nuevo.
-- Correr conectado a 'carnisys' con el rol carnisys_admin (dueno de las tablas).
-- IMPORTANTE: carnisys_sysadmin_bypass (alta de empresas y sucursales, SystemAdministrationPg) es BYPASSRLS pero
-- BYPASSRLS no exime de los GRANT de objeto: sin los GRANT del final el alta de empresa falla con "permission denied".

CREATE TABLE IF NOT EXISTS titulares_fiscales (
    idtitular             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idempresa             integer NOT NULL,
    idpersona             integer,                         -- NULL solo en el titular principal (no hay persona)
    cuit                  bigint,                          -- principal: espejo de empresas.cuit; inmutable (es la carpeta AFIP/<cuit>)
    espredeterminado      boolean NOT NULL DEFAULT false,
    habilitado            boolean NOT NULL DEFAULT true,
    razonsocial           text,                            -- no principal: copia de la persona; principal: se lee de empresas
    idiva                 integer,                         -- 2 = Responsable Inscripto, 3 = Monotributo
    condicioniva          text,                            -- texto impreso en la factura (no principal)
    inicioactividad       date,
    iibb                  bigint,
    nombrecertificado_pfx text,
    limitemensual         numeric(18,2),                   -- NULL = sin tope
    limiteanual           numeric(18,2),                   -- NULL = sin tope
    ventanaanual          varchar(12) NOT NULL DEFAULT 'MOVIL12M',
    creado                timestamp NOT NULL DEFAULT now(),
    CONSTRAINT ck_titulares_ventanaanual CHECK (ventanaanual IN ('MOVIL12M', 'CALENDARIO')),
    CONSTRAINT ck_titulares_persona CHECK (idpersona IS NOT NULL OR espredeterminado)
);

-- Un CUIT = una carpeta de certificado = un solo titular en toda la base (los NULL no chocan).
CREATE UNIQUE INDEX IF NOT EXISTS ux_titulares_fiscales_cuit ON titulares_fiscales (cuit) WHERE cuit IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS ux_titulares_fiscales_persona ON titulares_fiscales (idempresa, idpersona) WHERE idpersona IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS ux_titulares_fiscales_principal ON titulares_fiscales (idempresa) WHERE espredeterminado;
CREATE INDEX IF NOT EXISTS ix_titulares_fiscales_empresa ON titulares_fiscales (idempresa);

CREATE TABLE IF NOT EXISTS titulares_fiscales_ptovta (
    idempresa           integer NOT NULL,
    idtitular           integer NOT NULL,
    codpuntoventaafip   integer NOT NULL,
    descripcion         text,
    habilitado          boolean NOT NULL DEFAULT true,
    origen              varchar(6) NOT NULL DEFAULT 'MANUAL',
    PRIMARY KEY (idtitular, codpuntoventaafip),
    CONSTRAINT ck_titulares_ptovta_origen CHECK (origen IN ('ARCA', 'MANUAL')),
    CONSTRAINT ck_titulares_ptovta_cod CHECK (codpuntoventaafip > 0)
);

CREATE TABLE IF NOT EXISTS titulares_fiscales_sucursal (
    idempresa           integer NOT NULL,
    idtitular           integer NOT NULL,
    idsucursal          integer NOT NULL,
    codpuntoventaafip   integer NOT NULL,
    PRIMARY KEY (idtitular, idsucursal)
);

CREATE TABLE IF NOT EXISTS titulares_fiscales_clave (
    idempresa           integer NOT NULL,
    idtitular           integer NOT NULL,
    entorno             varchar(4) NOT NULL,
    clave_protegida     text NOT NULL,
    actualizado         timestamp NOT NULL DEFAULT now(),
    PRIMARY KEY (idtitular, entorno),
    CONSTRAINT ck_titulares_clave_entorno CHECK (entorno IN ('PROD', 'HOMO'))
);

-- RLS estricta por idempresa en las 5 tablas (mismo patron que auditoriacierrecaja).
ALTER TABLE titulares_fiscales ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS titulares_fiscales_rls ON titulares_fiscales;
CREATE POLICY titulares_fiscales_rls ON titulares_fiscales FOR ALL
    USING (current_setting('app.id_empresa', true) IS NOT NULL AND current_setting('app.id_empresa', true) <> ''
           AND idempresa = current_setting('app.id_empresa', true)::int)
    WITH CHECK (idempresa = current_setting('app.id_empresa', true)::int);

