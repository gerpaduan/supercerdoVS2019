GRANT USAGE, SELECT ON SEQUENCE titulares_fiscales_idtitular_seq TO carnisys_sysadmin_bypass;

-- Backfill idempotente: un titular principal por cada empresa real (idempresa > 0; -1 es la plantilla de parametros).
-- Espeja empresas.cuit (puede ser NULL/0 en empresas sin CUIT cargado).
INSERT INTO titulares_fiscales (idempresa, idpersona, cuit, espredeterminado, habilitado)
SELECT e.idempresa, NULL, CASE WHEN e.cuit IS NULL OR e.cuit <= 0 THEN NULL ELSE e.cuit END, true, true
FROM empresas e
WHERE e.idempresa > 0
  AND NOT EXISTS (SELECT 1 FROM titulares_fiscales t WHERE t.idempresa = e.idempresa AND t.espredeterminado);
