-- POS sin conexion (2026-11-26, ver docs/DECISIONS.md "POS sin conexion: ventas en cola que se suben solas").
-- Clave unica de cada operacion del POS que viene con un codigo generado en el navegador (clientid):
--  - tipo 'venta': una venta (online con el interruptor PosOffline prendido, u offline subida despues). idregistro = ventas.idventa.
--  - tipo 'caja' : una apertura de caja hecha sin conexion y creada despues. idregistro = cierrecaja.id.
-- El indice unico (idempresa, clientid) es lo que garantiza que un reintento (respuesta perdida, PC que vuelve a subir la
-- cola, servidor reiniciado) NUNCA grabe dos veces: el INSERT va en la MISMA transaccion que la venta, asi que si choca
-- con el indice se deshace la venta entera y se devuelve la ya existente.
-- La tabla ventas NO se toca (decision del usuario 2026-11-26): lo que ya funciona no depende de esta migracion.
-- Columnas de la venta offline:
--  - fechalocal: hora de la operacion en la PC (la venta se graba con esa fecha).
--  - llegotarde: la caja del turno ya estaba cerrada cuando llego la venta (cambia los totales de esa caja).
--  - sincaja: no se encontro ninguna caja del vendedor que contenga la fecha de la venta.
--  - pendientefacturar: la forma de pago pedia factura automatica y sin conexion no se pudo emitir.
--  - difprecio: algun precio cobrado difiere del precio actual del servidor (el detalle va en 'detalle').
--  - causacorte: causa probable del corte que vio el POS ('sinred', 'sininternet', 'servidor').
-- Aditiva e idempotente. Base unica multi-tenant (RLS por idempresa).
-- ORDEN DE DEPLOY: correr ANTES de publicar el codigo y ANTES de prender PosOffline:Habilitado. Con el interruptor apagado el
-- codigo no toca esta tabla. Correr conectado a 'carnisys' con el rol carnisys_admin (dueno de las tablas).

CREATE TABLE IF NOT EXISTS posclaveunica (
    id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idempresa           integer NOT NULL,
    clientid            uuid NOT NULL,
    tipo                varchar(10) NOT NULL,
    idregistro          integer NOT NULL,
    origen              varchar(10) NOT NULL,
    idsucursal          integer NOT NULL,
    idusuario           integer NOT NULL,
    idusuariosync       integer NOT NULL,
    fechalocal          timestamp NOT NULL,
    recibido            timestamp NOT NULL DEFAULT now(),
    llegotarde          boolean NOT NULL DEFAULT false,
    sincaja             boolean NOT NULL DEFAULT false,
    pendientefacturar   boolean NOT NULL DEFAULT false,
    difprecio           boolean NOT NULL DEFAULT false,
    causacorte          varchar(20),
    versioncatalogo     varchar(40),
    detalle             text,
    CONSTRAINT ck_posclaveunica_tipo CHECK (tipo IN ('venta', 'caja')),
    CONSTRAINT ck_posclaveunica_origen CHECK (origen IN ('online', 'offline'))
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_posclaveunica_empresa_clientid ON posclaveunica (idempresa, clientid);
CREATE INDEX IF NOT EXISTS ix_posclaveunica_registro ON posclaveunica (idempresa, tipo, idregistro);
CREATE INDEX IF NOT EXISTS ix_posclaveunica_avisos ON posclaveunica (idempresa, idsucursal, recibido)
    WHERE llegotarde OR sincaja OR pendientefacturar OR difprecio;

ALTER TABLE posclaveunica ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS posclaveunica_rls ON posclaveunica;
CREATE POLICY posclaveunica_rls ON posclaveunica FOR ALL
    USING (current_setting('app.id_empresa', true) IS NOT NULL AND current_setting('app.id_empresa', true) <> ''
           AND idempresa = current_setting('app.id_empresa', true)::int)
    WITH CHECK (idempresa = current_setting('app.id_empresa', true)::int);

-- UPDATE: solo para bajar la marca pendientefacturar cuando la venta se factura despues.
GRANT SELECT, INSERT, UPDATE ON posclaveunica TO carnisys_user, cs_admin_pg;
GRANT USAGE, SELECT ON SEQUENCE posclaveunica_id_seq TO carnisys_user, cs_admin_pg;
