-- Titular propio en compras y pagos + comprobantes del proveedor (factura, nota de credito/debito) por compra
-- (2026-11-09, ver docs/DECISIONS.md "Compras: titular propio y comprobantes del proveedor").
--  - compras.idtitular / pagos.idtitular / movctacte.idtitular: a nombre de que titular fiscal propio se hizo la compra o
--    el pago. NULL = titular principal de la empresa (historia vieja y empresas con un solo titular). Sin FK (patron del repo).
--  - compras.estadofactura: PENDIENTE | FACTURADA | NO_LLEVA. NULL = compra anterior a esta migracion (sin dato, para que la
--    bandeja de pendientes no se llene de historia).
--  - comprobantescompra: una factura (maximo una activa) y las notas de credito/debito de una compra. NO generan movimientos de
--    cuenta corriente: la deuda es el importe de la compra (decision del usuario).
-- Aditiva e idempotente. Base unica multi-tenant (RLS por idempresa): una sola corrida cubre a todas las empresas.
-- ORDEN DE DEPLOY: correr ESTA migracion ANTES de publicar el codigo nuevo. Solo Postgres (en SQL Server no aplica).
-- Correr conectado a carnisys con el rol carnisys_admin (dueno de las tablas).

ALTER TABLE compras    ADD COLUMN IF NOT EXISTS idtitular     integer;
ALTER TABLE compras    ADD COLUMN IF NOT EXISTS estadofactura varchar(10);
ALTER TABLE pagos      ADD COLUMN IF NOT EXISTS idtitular     integer;
ALTER TABLE movctacte  ADD COLUMN IF NOT EXISTS idtitular     integer;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_compras_estadofactura') THEN
        ALTER TABLE compras ADD CONSTRAINT ck_compras_estadofactura
            CHECK (estadofactura IS NULL OR estadofactura IN ('PENDIENTE', 'FACTURADA', 'NO_LLEVA'));
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS ix_movctacte_persona_titular ON movctacte (idempresa, idpersona, idtitular);
CREATE INDEX IF NOT EXISTS ix_compras_estadofactura ON compras (idempresa, estadofactura) WHERE estadofactura IS NOT NULL;

CREATE TABLE IF NOT EXISTS comprobantescompra (
    idcomprobante      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idempresa          integer NOT NULL,
    idcompra           integer NOT NULL,
    idproveedor        integer NOT NULL,            -- copia de compras.idproveedor (para el indice anti-duplicado)
    tipocomprobante    varchar(30) NOT NULL,        -- Factura A/B/C/M, Nota de credito A/B/C/M, Nota de debito A/B/C/M, Otro
    ptovta             integer NOT NULL,
    numero             bigint NOT NULL,
    fecha              date NOT NULL,
    netogravado        numeric(14,2) NOT NULL DEFAULT 0,
    iva                numeric(14,2) NOT NULL DEFAULT 0,
    otrosimpuestos     numeric(14,2) NOT NULL DEFAULT 0,
    total              numeric(14,2) NOT NULL,      -- positivo: el signo sale del tipo de comprobante
    alicuotaiva        numeric(5,2),
    creado             timestamp NOT NULL DEFAULT now(),
    creadopor          integer,
    actualizado        timestamp,
    actualizadopor     integer,
    eliminado          boolean NOT NULL DEFAULT false,
    eliminadopor       integer,
    eliminadofecha     timestamp,
    motivoeliminacion  text,
    CONSTRAINT ck_comprobantescompra_ptovta CHECK (ptovta >= 0),
    CONSTRAINT ck_comprobantescompra_total CHECK (total >= 0)
);

CREATE INDEX IF NOT EXISTS ix_comprobantescompra_compra ON comprobantescompra (idempresa, idcompra) WHERE NOT eliminado;
-- Un mismo comprobante (proveedor + tipo + punto de venta + numero) no se carga dos veces.
CREATE UNIQUE INDEX IF NOT EXISTS ux_comprobantescompra_numero
    ON comprobantescompra (idempresa, idproveedor, tipocomprobante, ptovta, numero) WHERE NOT eliminado;

ALTER TABLE comprobantescompra ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS comprobantescompra_rls ON comprobantescompra;
CREATE POLICY comprobantescompra_rls ON comprobantescompra FOR ALL
    USING (current_setting('app.id_empresa', true) IS NOT NULL AND current_setting('app.id_empresa', true) <> ''
           AND idempresa = current_setting('app.id_empresa', true)::int)
    WITH CHECK (idempresa = current_setting('app.id_empresa', true)::int);

GRANT SELECT, INSERT, UPDATE, DELETE ON comprobantescompra TO carnisys_user, cs_admin_pg;
GRANT USAGE, SELECT ON SEQUENCE comprobantescompra_idcomprobante_seq TO carnisys_user, cs_admin_pg;
