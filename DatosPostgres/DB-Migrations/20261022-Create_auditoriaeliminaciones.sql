-- Eliminacion de Compras, Stock y Movimientos con motivo y clave (2026-10-22, ver docs/DECISIONS.md
-- "Eliminar compras, stock y movimientos"). Correr como carnisys_admin (dueno de las tablas), ANTES de desplegar el codigo.
-- Un registro eliminado SE BORRA de su tabla; esta auditoria conserva quien lo elimino, cuando, el motivo
-- y la foto completa de lo que tenia (cabecera + lineas). Append-only: solo INSERT/SELECT.

CREATE TABLE IF NOT EXISTS auditoriaeliminaciones (
    id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idempresa           integer      NOT NULL,
    modulo              varchar(12)  NOT NULL,
    idregistro          integer      NOT NULL,
    tiporegistro        varchar(100),
    fecharegistro       timestamp,
    idsucursal          integer,
    idsucursaldestino   integer,
    idpersona           integer,
    nroremito           varchar(100),
    enctacte            boolean,
    cantmedias          integer,
    kgsmedias           double precision,
    importe             double precision,
    totalkg             double precision,
    cantlineas          integer      NOT NULL DEFAULT 0,
    observaciones       text,
    idusuariocreador    integer,
    creado              timestamp,
    idusuarioelimino    integer      NOT NULL,
    idusuariosesion     integer      NOT NULL,
    fechaeliminacion    timestamp    NOT NULL DEFAULT now(),
    motivo              text         NOT NULL,
    ip                  varchar(60),
    efectos             text,
    CONSTRAINT ck_auditoriaeliminaciones_modulo CHECK (modulo IN ('COMPRA', 'STOCK', 'MOVIMIENTO'))
);

CREATE INDEX IF NOT EXISTS ix_auditoriaeliminaciones_registro ON auditoriaeliminaciones (idempresa, modulo, idregistro);
CREATE INDEX IF NOT EXISTS ix_auditoriaeliminaciones_fecha ON auditoriaeliminaciones (idempresa, fechaeliminacion DESC);

-- Una fila por linea eliminada (producto o media res). El nombre y el codigo se copian: el producto puede cambiar despues.
CREATE TABLE IF NOT EXISTS auditoriaeliminacionlineas (
    id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idempresa           integer      NOT NULL,
    idauditoria         integer      NOT NULL,
    idcorte             integer,
    codigo              bigint,
    producto            text,
    idsucursal          integer,
    cantkg              double precision,
    cantunidad          integer,
    preciokg            double precision,
    detalle             text
);

CREATE INDEX IF NOT EXISTS ix_auditoriaeliminacionlineas_auditoria ON auditoriaeliminacionlineas (idempresa, idauditoria);

ALTER TABLE auditoriaeliminaciones ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS auditoriaeliminaciones_rls ON auditoriaeliminaciones;
CREATE POLICY auditoriaeliminaciones_rls ON auditoriaeliminaciones FOR ALL
    USING (current_setting('app.id_empresa', true) IS NOT NULL AND current_setting('app.id_empresa', true) <> ''
           AND idempresa = current_setting('app.id_empresa', true)::int)
    WITH CHECK (idempresa = current_setting('app.id_empresa', true)::int);

ALTER TABLE auditoriaeliminacionlineas ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS auditoriaeliminacionlineas_rls ON auditoriaeliminacionlineas;
CREATE POLICY auditoriaeliminacionlineas_rls ON auditoriaeliminacionlineas FOR ALL
    USING (current_setting('app.id_empresa', true) IS NOT NULL AND current_setting('app.id_empresa', true) <> ''
           AND idempresa = current_setting('app.id_empresa', true)::int)
    WITH CHECK (idempresa = current_setting('app.id_empresa', true)::int);

GRANT SELECT, INSERT ON auditoriaeliminaciones, auditoriaeliminacionlineas TO carnisys_user, cs_admin_pg;
GRANT USAGE, SELECT ON SEQUENCE auditoriaeliminaciones_id_seq, auditoriaeliminacionlineas_id_seq TO carnisys_user, cs_admin_pg;
