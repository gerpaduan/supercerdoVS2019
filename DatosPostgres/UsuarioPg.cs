        public List<Entidades.Usuario> BuscarUsuariosPorIdentificador(string identificador, bool soloActivos)
        {
            identificador = (identificador ?? string.Empty).Trim();
            if (identificador.Length == 0)
                return new List<Entidades.Usuario>();

            return ReaderSinRLS(@"
                SELECT *
                FROM usuarios
                WHERE (@soloActivos = false OR activo = true)
                  AND (
                    LOWER(COALESCE(usuario, '')) = LOWER(@identificador)
                    OR LOWER(COALESCE(email, '')) = LOWER(@identificador)
                  )
                ORDER BY activo DESC, id ASC;",
                dr => MapUsuario(dr),
                p =>
                {
                    p.AddWithValue("identificador", identificador);
                    p.AddWithValue("soloActivos", soloActivos);
                });
        }

        // Chequeo global (todas las empresas) de unicidad de nombre de usuario -- el candado de
        // verdad es el indice unico de la migracion 20260821; esto es solo para un mensaje de
        // error legible. Cruza todas las empresas a proposito, igual que BuscarUsuariosPorIdentificador.
        public bool existeUsuario(string usuario, int idExcluir)
        {
            usuario = (usuario ?? "").Trim();
            if (usuario.Length == 0) return false;

            var lista = ReaderSinRLS(
                "SELECT 1 FROM usuarios WHERE LOWER(usuario) = LOWER(@usuario) AND id <> @idExcluir LIMIT 1;",
                dr => true,
                p =>
                {
                    p.AddWithValue("usuario", usuario);
                    p.AddWithValue("idExcluir", idExcluir);
                });
            return lista.Count > 0;
        }

