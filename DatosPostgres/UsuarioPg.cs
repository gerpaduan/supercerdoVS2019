    // fuera -- se agregan en etapas futuras (13c/13d). Ver docs/DECISIONS.md.
    //
    // "usuarios" y "usuariopasswordresettokens" SI tienen RLS (revertido de la decision anterior
    // documentada abajo, ver docs/DECISIONS.md 2026-08-21: se encontro que sin RLS, cualquier
    // query que se olvidara del WHERE idempresa filtraria usuarios de otro tenant, passwordhash
    // incluido -- confiar en que cada caller se acuerde de chequear a mano no escala). El
    // problema real: Login/OlvideMiContrasena/ResetPassword/UnlockAccount corren SIN saber a que
    // empresa pertenece el usuario todavia -- necesitan buscar cruzando todas las empresas. Los
    // pocos metodos que lo necesitan usan AbrirSinRLS (mas abajo, `SET LOCAL ROLE
    // carnisys_usuarios_bypass` scopeado a esa transaccion puntual, ver migracion 20260821b y
    // docs/DECISIONS.md); el resto de la clase sigue protegida por RLS sin cambios.
    //
    // "id" es GENERATED BY DEFAULT AS IDENTITY -- el SP original de SQL Server calculaba
    // MAX(id)+1 con UPDLOCK/HOLDLOCK (con un comentario propio marcando el riesgo de
    // concurrencia); decision del usuario: se resuelve de raiz con identity en vez de
    // replicar esa limitacion.
    public class UsuarioPg : Contratos.IUsuarioRepository
    {
        private readonly string _connectionString;
        private readonly int _idEmpresa;
        private readonly Contratos.ISucursalRepository _sucursalRepo;

        public UsuarioPg(string connectionString, int idEmpresa, Contratos.ISucursalRepository sucursalRepo)
        {
            if (string.IsNullOrWhiteSpace(connectionString)) throw new ArgumentNullException(nameof(connectionString));
            _connectionString = connectionString;
            _idEmpresa = idEmpresa;
            _sucursalRepo = sucursalRepo ?? throw new ArgumentNullException(nameof(sucursalRepo));
        }

        #region Helpers sin RLS (login/recuperacion de contraseña, tenant desconocido)

        // Abre una conexion+transaccion propia asumiendo el rol carnisys_usuarios_bypass (ver
        // migracion 20260821b) -- SOLO para los pocos metodos de esta clase que legitimamente
        // necesitan buscar cruzando todas las empresas (ver comentario de clase).
        //
        // NO usa "SET LOCAL row_security = off": Postgres RECHAZA esa sentencia con error 42501
        // si el rol no tiene ya BYPASSRLS -- no existe forma de desactivar RLS "por esta vez"
        // sin el privilegio real (encontrado probando el login real, ver docs/DECISIONS.md
        // 2026-08-21). SET LOCAL ROLE si funciona: el efecto vive y muere con la transaccion
        // (revierte solo al hacer commit/rollback), igual que app.id_empresa en
        // ConexionPg.AbrirConTenant -- una conexion reciclada por el pool nunca puede arrastrar
        // esto a la proxima request. Verificado a mano que la membresia de carnisys_user en
        // carnisys_usuarios_bypass NO habilita el bypass fuera de este SET LOCAL ROLE explicito.
        private NpgsqlConnection AbrirSinRLS(out NpgsqlTransaction tx)
        {
            var cn = new NpgsqlConnection(_connectionString);
            cn.Open();
            tx = cn.BeginTransaction();
            using (var cmd = new NpgsqlCommand("SET LOCAL ROLE carnisys_usuarios_bypass;", cn, tx))
                cmd.ExecuteNonQuery();
            return cn;
        }

        private void NonQuerySinRLS(string sql, Action<NpgsqlParameterCollection> setParams)
        {
            using (var cn = AbrirSinRLS(out var tx))
            {
                try
                {
                    using (var cmd = new NpgsqlCommand(sql, cn, tx))
                    {
                        setParams?.Invoke(cmd.Parameters);
                        cmd.ExecuteNonQuery();
                    }
                    tx.Commit();
                }
                catch { tx.Rollback(); throw; }
            }
        }

        private List<T> ReaderSinRLS<T>(string sql, Func<NpgsqlDataReader, T> map, Action<NpgsqlParameterCollection> setParams)
        {
            using (var cn = AbrirSinRLS(out var tx))
            {
                try
                {
                    var lista = new List<T>();
                    using (var cmd = new NpgsqlCommand(sql, cn, tx))
                    {
                        setParams?.Invoke(cmd.Parameters);
                        using (var dr = cmd.ExecuteReader())
                        {
                            while (dr.Read())
                                lista.Add(map(dr));
                        }
                    }
                    tx.Commit();
                    return lista;
                }
                catch { tx.Rollback(); throw; }
            }
        }

        private DataTable DataTableSinRLS(string sql, Action<NpgsqlParameterCollection> setParams)
        {
            using (var cn = AbrirSinRLS(out var tx))
            {
                try
                {
                    var dt = new DataTable();
                    using (var cmd = new NpgsqlCommand(sql, cn, tx))
                    using (var da = new NpgsqlDataAdapter(cmd))
                    {
                        setParams?.Invoke(cmd.Parameters);
                        da.Fill(dt);
                    }
                    tx.Commit();
                    return dt;
                }
                catch { tx.Rollback(); throw; }
            }
        }

        #endregion

        #region Helpers

        private static bool ColumnaExiste(NpgsqlDataReader dr, string columna)
        {
            try { return dr.GetOrdinal(columna) >= 0; } catch { return false; }
        }

        private static string GetString(NpgsqlDataReader dr, string columna) =>
            ColumnaExiste(dr, columna) && dr[columna] != DBNull.Value ? Convert.ToString(dr[columna]) : "";

        private static int GetInt(NpgsqlDataReader dr, string columna) =>
            ColumnaExiste(dr, columna) && dr[columna] != DBNull.Value ? Convert.ToInt32(dr[columna]) : 0;

        private static bool GetBool(NpgsqlDataReader dr, string columna) =>
            ColumnaExiste(dr, columna) && dr[columna] != DBNull.Value && Convert.ToBoolean(dr[columna]);

        private Entidades.Usuario MapUsuario(NpgsqlDataReader dr)
        {
            return new Entidades.Usuario
            {
                Id = Convert.ToInt32(dr["id"]),
                Nombre = GetString(dr, "nombre"),
                User = GetString(dr, "usuario"),
                Clave = GetString(dr, "clave"),
                Email = GetString(dr, "email"),
                PasswordHash = GetString(dr, "passwordhash"),
                PasswordSalt = GetString(dr, "passwordsalt"),
                PasswordHashIterations = GetInt(dr, "passwordhashiterations"),
                PasswordUpdatedAtUtc = dr["passwordupdatedatutc"] == DBNull.Value ? (DateTime?)null : Convert.ToDateTime(dr["passwordupdatedatutc"]),
                Admin = GetBool(dr, "admin"),
                Activo = GetBool(dr, "activo"),
                ColorForm = GetString(dr, "colorform"),
                IdSucursal = dr["idsucursaluser"] == DBNull.Value ? 0 : Convert.ToInt32(dr["idsucursaluser"]),
                IdEmpresa = dr["idempresa"] == DBNull.Value ? 0 : Convert.ToInt32(dr["idempresa"]),
                PermitirLoginFueraSucursal = GetBool(dr, "permitirloginfuerasucursal"),
                EsUsuarioProduccion = GetBool(dr, "esusuarioproduccion"),
                IntentosFallidosLogin = GetInt(dr, "intentosfallidoslogin"),
                Bloqueado = GetBool(dr, "bloqueado"),
                FechaBloqueoUtc = dr["fechabloqueoutc"] == DBNull.Value ? (DateTime?)null : Convert.ToDateTime(dr["fechabloqueoutc"])
            };
        }

        #endregion

        public DataTable obtenerUsuarios(bool soloActivos, bool filtroEmpresa = true, bool soloAdmin = false)
        {
            if (soloAdmin)
            {
                // Cruza todas las empresas a proposito -- "admin" es una cuenta global (ver
                // comentario de clase). Sin caller real desde Web hoy (solo Presentacion/
                // WinForms, que nunca toca Postgres), pero implementado igual por las dudas.
                return DataTableSinRLS(
                    "SELECT * FROM usuarios WHERE usuario = @usuario;",
                    p => p.AddWithValue("usuario", "admin"));
            }

            if (!filtroEmpresa)
            {
                // Camino de login: busca cruzando todas las empresas porque todavia no se sabe
                // a cual pertenece el usuario (ver comentario de clase).
                var whereSinFiltro = new List<string>();
                if (soloActivos) whereSinFiltro.Add("activo = true");
                string sqlSinFiltro = "SELECT * FROM usuarios" + (whereSinFiltro.Count > 0 ? " WHERE " + string.Join(" AND ", whereSinFiltro) : "");
                return DataTableSinRLS(sqlSinFiltro, null);
            }

            var where = new List<string>();
            where.Add("idempresa = @idEmpresa");
            if (soloActivos) where.Add("activo = true");

            string sql = "SELECT * FROM usuarios WHERE " + string.Join(" AND ", where);

            return DbPg.DataTable(_connectionString, _idEmpresa, sql, p => p.AddWithValue("idEmpresa", _idEmpresa));
        }

        public DataTable getUsuarioActivos()
        {
            return DbPg.DataTable(_connectionString, _idEmpresa,
                "SELECT nombre, usuario, clave FROM usuarios WHERE activo = true AND idempresa = @idEmpresa;",
                p => p.AddWithValue("idEmpresa", _idEmpresa));
        }

        public Entidades.Usuario getUsuarioById(int idUsuario, bool sinRestriccionDeTenant = false)
        {
            const string sql = "SELECT * FROM usuarios WHERE id = @id;";
            var list = sinRestriccionDeTenant
                ? ReaderSinRLS(sql, dr => MapUsuario(dr), p => p.AddWithValue("id", idUsuario))
                : DbPg.Reader(_connectionString, _idEmpresa, sql, dr => MapUsuario(dr), p => p.AddWithValue("id", idUsuario));

            if (list.Count == 0) return null;

            var usuario = list[0];
            usuario.Sucursal = usuario.IdSucursal > 0 ? _sucursalRepo.findById(usuario.IdSucursal) : null;
            usuario.Empresa = usuario.IdEmpresa > 0 ? _sucursalRepo.findEmpresaById(usuario.IdEmpresa) : null;
            return usuario;
        }

        // Transaccion explicita: alta de usuario + permisos por defecto son atomicos (mismo
        // patron que el SP original, que hace todo en un BEGIN TRAN/COMMIT). Rama de alta usa
        // "INSERT ... RETURNING id" (columna identity) en vez de MAX(id)+1 -- ver comentario de
        // clase. Los 12 formularios/valores por defecto son los mismos que el SP original
        // hardcodea via LEFT JOIN (VALUES ...).
        public void addOrEditUser(Entidades.Usuario oUsuarioE)
        {
            using (var con = ConexionPg.AbrirConTenant(_connectionString, _idEmpresa, out var tx))
            {
                try
                {
                    if (oUsuarioE.Id == 0)
                    {
                        int idSucursal = oUsuarioE.IdSucursal;
                        if (idSucursal <= 0)
                        {
                            using (var cmdSuc = new NpgsqlCommand(
                                "SELECT idsucursal FROM sucursal WHERE idempresa = @idEmpresa ORDER BY idsucursal LIMIT 1;", con, tx))
                            {
                                cmdSuc.Parameters.AddWithValue("idEmpresa", _idEmpresa);
                                object sucObj = cmdSuc.ExecuteScalar();
                                idSucursal = (sucObj == null || sucObj == DBNull.Value) ? 0 : Convert.ToInt32(sucObj);
                            }
                        }

                        if (_idEmpresa <= 0)
                            throw new InvalidOperationException("IdEmpresa invalido.");
                        if (idSucursal <= 0)
                            throw new InvalidOperationException("No existe sucursal para la empresa indicada.");

                        int nuevoId;
                        using (var cmd = new NpgsqlCommand(@"
                            INSERT INTO usuarios (nombre, usuario, clave, email, admin, activo, colorform, idsucursaluser, idempresa)
                            VALUES (@nombre, @usuario, @clave, @email, @admin, @activo, @colorForm, @idSucursal, @idEmpresa)
                            RETURNING id;", con, tx))
                        {
                            cmd.Parameters.AddWithValue("nombre", oUsuarioE.Nombre ?? "");
                            cmd.Parameters.AddWithValue("usuario", oUsuarioE.User ?? "");
                            cmd.Parameters.AddWithValue("clave", oUsuarioE.Clave ?? "");
                            cmd.Parameters.AddWithValue("email", oUsuarioE.Email ?? "");
                            cmd.Parameters.AddWithValue("admin", oUsuarioE.Admin);
                            cmd.Parameters.AddWithValue("activo", oUsuarioE.Activo);
                            cmd.Parameters.AddWithValue("colorForm", oUsuarioE.ColorForm ?? "");
                            cmd.Parameters.AddWithValue("idSucursal", idSucursal);
                            cmd.Parameters.AddWithValue("idEmpresa", _idEmpresa);
                            nuevoId = Convert.ToInt32(cmd.ExecuteScalar());
                        }

                        oUsuarioE.Id = nuevoId;

                        using (var cmdPerm = new NpgsqlCommand(@"
                            INSERT INTO permisosusuarios (idusuario, idform, diaspermitidosver, diaspermitidoseditar, soloregistrospropios, idempresa)
                            SELECT
                                @id,
                                f.idform,
                                COALESCE(v.diasver, -1),
                                COALESCE(v.diaseditar, -1),
                                COALESCE(v.propios, true),
                                @idEmpresa
                            FROM formularios f
                            LEFT JOIN (VALUES
                                (3,  -1,  0, true),
                                (10, -1,  0, true),
                                (19,  0,  0, false),
                                (21,  0, -1, false),
                                (1,   0,  0, false),
                                (2,  -1,  0, false),
                                (32,  0, -1, false),
                                (18, 14,  0, true),
                                (33,  0,  0, true),
                                (34,  0,  0, true),
                                (5,   0,  0, false),
                                (12, -1,  0, false)
                            ) AS v(idform, diasver, diaseditar, propios)
                                ON f.idform = v.idform;", con, tx))
                        {
                            cmdPerm.Parameters.AddWithValue("id", nuevoId);
                            cmdPerm.Parameters.AddWithValue("idEmpresa", _idEmpresa);
                            cmdPerm.ExecuteNonQuery();
                        }
                    }
                    else
                    {
                        using (var cmd = new NpgsqlCommand(@"
                            UPDATE usuarios SET
                                nombre = @nombre,
                                usuario = @usuario,
                                clave = @clave,
                                email = @email,
                                admin = @admin,
                                activo = @activo,
                                colorform = @colorForm
                            WHERE id = @id;", con, tx))
                        {
                            cmd.Parameters.AddWithValue("id", oUsuarioE.Id);
                            cmd.Parameters.AddWithValue("nombre", oUsuarioE.Nombre ?? "");
                            cmd.Parameters.AddWithValue("usuario", oUsuarioE.User ?? "");
                            cmd.Parameters.AddWithValue("clave", oUsuarioE.Clave ?? "");
                            cmd.Parameters.AddWithValue("email", oUsuarioE.Email ?? "");
                            cmd.Parameters.AddWithValue("admin", oUsuarioE.Admin);
                            cmd.Parameters.AddWithValue("activo", oUsuarioE.Activo);
                            cmd.Parameters.AddWithValue("colorForm", oUsuarioE.ColorForm ?? "");
                            cmd.ExecuteNonQuery();
                        }
                    }

                    tx?.Commit();
                }
                catch
                {
                    try { tx?.Rollback(); } catch { }
                    throw;
                }
            }
        }

